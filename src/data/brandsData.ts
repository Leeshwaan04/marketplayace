// All brands are real. Filter functions below return real brands ONLY.
export const FLAGSHIP_BRANDS = REAL_BRANDS

export function generateCategoryBrands(categorySlug: string): Brand[] {
  // Return real brands matching the category, or all real brands if "all"
  const matches = REAL_BRANDS.filter((b) => b.category === categorySlug)
  if (matches.length > 0) return matches
  // If specific niche category has no direct flagship, return relevant real brands
  return REAL_BRANDS
}

export function generateCountryBrands(countrySlug: string, citySlug?: string): Brand[] {
  return REAL_BRANDS.filter((b) => {
    const matchesCountry =
      b.country.toLowerCase() === countrySlug.toLowerCase() ||
      b.countryCode.toLowerCase() === countrySlug.toLowerCase() ||
      (countrySlug === 'united-states' && b.countryCode === 'US') ||
      (countrySlug === 'india' && b.countryCode === 'IN') ||
      (countrySlug === 'united-kingdom' && b.countryCode === 'GB') ||
      (countrySlug === 'uae' && b.countryCode === 'AE') ||
      (countrySlug === 'singapore' && b.countryCode === 'SG') ||
      (countrySlug === 'germany' && b.countryCode === 'DE') ||
      (countrySlug === 'japan' && b.countryCode === 'JP') ||
      (countrySlug === 'canada' && b.countryCode === 'CA')

    if (!matchesCountry) return false

    if (citySlug) {
      const normalizedCitySlug = citySlug.replace(/-/g, ' ').toLowerCase()
      return b.city.toLowerCase().includes(normalizedCitySlug)
    }

    return true
  })
}
